def width(text, s=1):
    return (len(text) * 4 - 1) * s


def draw(px, x, y, text, col, s=1):
    """px: numpy RGBA array; draws text with top-left at (x, y), scale s"""
    for i, ch in enumerate(text.upper()):
        g = G.get(ch, G[' '])
        for k, c in enumerate(g):
            if c != '#': continue
            gx, gy = x + (i * 4 + k % 3) * s, y + (k // 3) * s
            px[gy:gy + s, gx:gx + s] = col
